using System.Diagnostics;
using Ivy.Tendril.Wireframe.Assets;
using Ivy.Tendril.Wireframe.Project;

namespace Ivy.Tendril.Wireframe.Build;

/// <summary>
/// Runs the Tailwind standalone CLI over the project's own source, for
/// <c>--tailwind jit</c>.
///
/// The output replaces the embedded utility superset; the library's own tendril.css is
/// unchanged and still loads first, so the cascade layers behave exactly as they do in
/// the default mode.
/// </summary>
public sealed class TailwindCompiler(string tailwindPath, AssetCatalog assets, WireframeProject project)
{
    /// <summary>Where the generated sheet lands. Served in place of the embedded one.</summary>
    public static string OutputPath(WireframeProject project) =>
        Path.Combine(project.OutDir("css"), "wireframe-utilities.css");

    /// <summary>
    /// Writes the Tailwind entry point.
    ///
    /// Two things match the embedded build exactly, and both matter: no preflight (the
    /// library sheet already ships one, and a second reset applies twice), and the theme
    /// and utilities layers imported individually so the output lands in the same cascade
    /// layers tendril.css declares.
    /// </summary>
    private string WriteInput()
    {
        var workDir = Path.Combine(project.WorkDir, "tailwind");
        Directory.CreateDirectory(workDir);

        // The theme tokens have to exist on disk for Tailwind to @import them.
        var themePath = Path.Combine(workDir, "theme.css");
        File.WriteAllBytes(themePath, assets.Read("css/theme.css"));

        var source = project.SourceDir.Replace('\\', '/');
        var input = string.Join('\n',
        [
            "/* GENERATED by `wireframe --tailwind jit` -- do not edit. */",
            "@import \"tailwindcss/theme.css\" layer(theme);",
            "@import \"tailwindcss/utilities.css\" layer(utilities);",
            "@import \"./theme.css\";",
            "",
            "/* Scan the agent's own source. The library's classes are already covered by",
            "   tendril.css, which loads ahead of this sheet. */",
            $"@source \"{source}\";",
            "",
        ]);

        var inputPath = Path.Combine(workDir, "input.css");
        File.WriteAllText(inputPath, input);
        return inputPath;
    }

    private ProcessStartInfo StartInfo(string inputPath, bool watch)
    {
        var psi = new ProcessStartInfo(tailwindPath)
        {
            RedirectStandardError = true,
            RedirectStandardOutput = true,
            // Like esbuild, the Tailwind CLI stops watching as soon as stdin closes.
            // Holding the pipe keeps it alive, and breaking it on our exit means no
            // orphaned watcher is left behind.
            RedirectStandardInput = watch,
            UseShellExecute = false,
            WorkingDirectory = project.Root,
        };

        psi.ArgumentList.Add("--input");
        psi.ArgumentList.Add(inputPath);
        psi.ArgumentList.Add("--output");
        psi.ArgumentList.Add(OutputPath(project));
        psi.ArgumentList.Add("--minify");
        if (watch) psi.ArgumentList.Add("--watch");

        return psi;
    }

    /// <summary>One clean compile, for `screenshot`.</summary>
    public async Task<BuildResult> CompileOnceAsync(CancellationToken ct = default)
    {
        Directory.CreateDirectory(project.OutDir("css"));

        using var process = Process.Start(StartInfo(WriteInput(), watch: false))
            ?? throw new InvalidOperationException($"Could not start Tailwind at {tailwindPath}");

        var stderr = await process.StandardError.ReadToEndAsync(ct);
        await process.StandardOutput.ReadToEndAsync(ct);
        await process.WaitForExitAsync(ct);

        return new BuildResult(process.ExitCode == 0, stderr.Trim());
    }

    /// <summary>
    /// Long-lived <c>--watch</c>, for `serve`. Returns once the first sheet is on disk, so
    /// the server never serves a 404 for the stylesheet.
    /// </summary>
    public async Task<IAsyncDisposable> StartWatchAsync(CancellationToken ct = default)
    {
        Directory.CreateDirectory(project.OutDir("css"));

        var process = Process.Start(StartInfo(WriteInput(), watch: true))
            ?? throw new InvalidOperationException($"Could not start Tailwind at {tailwindPath}");

        _ = Task.Run(async () =>
        {
            try { await process.StandardError.ReadToEndAsync(ct); } catch { /* shutting down */ }
        }, CancellationToken.None);
        _ = Task.Run(async () =>
        {
            try { await process.StandardOutput.ReadToEndAsync(ct); } catch { /* shutting down */ }
        }, CancellationToken.None);

        var output = OutputPath(project);
        var deadline = DateTime.UtcNow.AddSeconds(30);
        while (DateTime.UtcNow < deadline)
        {
            if (File.Exists(output) && new FileInfo(output).Length > 0) break;
            if (process.HasExited)
                throw new InvalidOperationException(
                    $"Tailwind exited with code {process.ExitCode} before writing a stylesheet.");
            await Task.Delay(50, ct);
        }

        return new ProcessHandle(process);
    }

    private sealed class ProcessHandle(Process process) : IAsyncDisposable
    {
        public async ValueTask DisposeAsync()
        {
            if (!process.HasExited)
            {
                try
                {
                    process.Kill(entireProcessTree: true);
                    await process.WaitForExitAsync();
                }
                catch
                {
                    // Already gone.
                }
            }
            process.Dispose();
        }
    }
}
